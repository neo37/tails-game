/**
 * Ники — только из готовых слов, как названия трасс: «Смелая Лиса», «Шустрый Ёж».
 * Свободного текста, который увидят чужие игроки, в игре нет (правило магазинов для контента от игроков).
 * Чужие имена, что приходят с сервера (старые версии игры могли прислать что угодно),
 * показываем, только если они из этих слов, иначе — «Игрок».
 * Все сочетания не длиннее 14 символов — столько пропускает сервер.
 */
export const NICK_ADJ = [         // [мужской род, женский]
  ['Смелый', 'Смелая'], ['Быстрый', 'Быстрая'], ['Весёлый', 'Весёлая'], ['Хитрый', 'Хитрая'],
  ['Тихий', 'Тихая'], ['Ловкий', 'Ловкая'], ['Добрый', 'Добрая'], ['Лунный', 'Лунная'],
  ['Рыжий', 'Рыжая'], ['Мудрый', 'Мудрая'], ['Сонный', 'Сонная'], ['Шустрый', 'Шустрая'],
  ['Храбрый', 'Храбрая'], ['Морской', 'Морская'], ['Лесной', 'Лесная'], ['Снежный', 'Снежная'],
];
export const NICK_WHO = [         // [слово, род: 0 — мужской, 1 — женский]
  ['Лис', 0], ['Кот', 0], ['Ёж', 0], ['Волк', 0], ['Тигр', 0], ['Енот', 0], ['Филин', 0], ['Кит', 0],
  ['Лиса', 1], ['Кошка', 1], ['Сова', 1], ['Белка', 1], ['Панда', 1], ['Пчела', 1], ['Выдра', 1], ['Чайка', 1],
];
export const ANON = 'Игрок';

export const nickOf = (a, w) => `${NICK_ADJ[a][NICK_WHO[w][1]]} ${NICK_WHO[w][0]}`;
const ALL = new Map();            // ник → [a, w]
NICK_ADJ.forEach((_, a) => NICK_WHO.forEach((__, w) => ALL.set(nickOf(a, w), [a, w])));

export const isNick = (s) => ALL.has(s);
/** Номера слов ника ([прилагательное, кто]) или null. */
export const nickParts = (s) => ALL.get(s) || null;
export const randomNick = () => nickOf(Math.floor(Math.random() * NICK_ADJ.length), Math.floor(Math.random() * NICK_WHO.length));
/** Чужое имя для показа: ник из готовых слов — как есть, иначе «Игрок». */
export const safeName = (s) => (isNick(s) ? s : ANON);
